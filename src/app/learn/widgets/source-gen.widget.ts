import { Component, computed, signal } from '@angular/core';
import { CodeViewComponent } from '../shared/code-view.component';

type Mode = 'tostring' | 'observable';
interface Field { name: string; type: string; on: boolean }

/** Edit the code you write and watch the code a source generator adds at compile time. */
@Component({
  selector: 'w-source-gen',
  standalone: true,
  imports: [CodeViewComponent],
  template: `
    <div class="widget">
      <div class="w-head"><span class="badge-try">Interactive</span><h3>Code that writes code</h3></div>
      <div class="w-controls" role="group" aria-label="Generator">
        <button type="button" class="w-btn mono" [class.on]="mode() === 'tostring'" (click)="mode.set('tostring')" [attr.aria-pressed]="mode() === 'tostring'">[AutoToString]</button>
        <button type="button" class="w-btn mono" [class.on]="mode() === 'observable'" (click)="mode.set('observable')" [attr.aria-pressed]="mode() === 'observable'">[ObservableProperty]</button>
      </div>
      <div class="w-controls" role="group" aria-label="Members">
        <span class="small text-muted">Members:</span>
        @for (f of fields(); track f.name) {
          <label class="chk mono"><input type="checkbox" [checked]="f.on" (change)="toggle(f.name)"> {{ f.name }}</label>
        }
      </div>
      <ol class="flow small" aria-label="Build steps">
        <li>you write <b>{{ mine() }}</b></li><li>compiler parses it</li><li>generator runs</li><li>adds <b>{{ genFile() }}</b></li><li>both compile into one class</li>
      </ol>
      <div class="w-grid two">
        <app-code [code]="userCode()" [title]="mine() + ' (you write)'" [compact]="true" [copyable]="false" />
        <app-code [code]="generated()" [title]="genFile() + ' (generated)'" [compact]="true" [copyable]="false" />
      </div>
      <div class="w-msg info" aria-live="polite"><i class="bi bi-magic" aria-hidden="true"></i><span>{{ note() }}</span></div>
    </div>
  `,
  styleUrls: ['./widget.scss'],
  styles: [`
    .chk { display: inline-flex; gap: 5px; align-items: center; font-size: 0.82rem; }
    .chk input { accent-color: var(--purple); }
    .flow { list-style: none; display: flex; flex-wrap: wrap; gap: 4px; padding: 0; margin: 0 0 0.8rem; counter-reset: s; }
    .flow li { counter-increment: s; padding: 3px 9px; border-radius: 999px; border: 1px solid var(--border-color); background: var(--bg-main); }
    .flow li::before { content: counter(s) '. '; color: var(--purple); font-weight: 700; }
  `]
})
export class SourceGenWidget {
  mode = signal<Mode>('tostring');
  private readonly all = signal<Field[]>([
    { name: 'Mark', type: 'string', on: true },
    { name: 'Profile', type: 'string', on: true },
    { name: 'LengthM', type: 'double', on: true },
    { name: 'Level', type: 'int', on: false }
  ]);
  fields = this.all.asReadonly();

  toggle(name: string) { this.all.update(fs => fs.map(f => (f.name === name ? { ...f, on: !f.on } : f))); }

  private on = computed(() => this.all().filter(f => f.on));
  private cls = computed(() => (this.mode() === 'tostring' ? 'Beam' : 'BeamViewModel'));
  mine = computed(() => this.cls() + '.cs');
  genFile = computed(() => this.cls() + (this.mode() === 'tostring' ? '.ToString.g.cs' : '.g.cs'));

  private field(n: string) { return '_' + n[0].toLowerCase() + n.slice(1); }
  private init(t: string) { return t === 'string' ? ' = ""' : ''; }

  userCode = computed(() => {
    const fs = this.on();
    if (this.mode() === 'tostring') {
      return ['[AutoToString]', 'public partial class Beam', '{',
        ...fs.map(f => `    public ${f.type} ${f.name} { get; set; }${this.init(f.type)}${f.type === 'string' ? ';' : ''}`),
        '}'].join('\n');
    }
    return ['public partial class BeamViewModel : ObservableObject', '{',
      ...fs.flatMap((f, i) => [...(i ? [''] : []), '    [ObservableProperty]', `    private ${f.type} ${this.field(f.name)}${this.init(f.type)};`]),
      '}'].join('\n');
  });

  generated = computed(() => {
    const fs = this.on();
    if (!fs.length) return '// no members: nothing to generate';
    if (this.mode() === 'tostring') {
      const body = fs.map(f => `"${f.name} = " + ${f.name}`).join(' + ", " + ');
      return ['// <auto-generated/>', 'partial class Beam', '{', '    public override string ToString() =>',
        `        "Beam { " + ${body} + " }";`, '}'].join('\n');
    }
    const lines = ['// <auto-generated/> (simplified)', 'partial class BeamViewModel', '{'];
    fs.forEach((f, i) => {
      const fld = this.field(f.name);
      if (i) lines.push('');
      lines.push(
        `    public ${f.type} ${f.name}`, '    {', `        get => ${fld};`, '        set', '        {',
        `            if (EqualityComparer<${f.type}>.Default.Equals(${fld}, value)) return;`,
        `            ${fld} = value;`, `            OnPropertyChanged(nameof(${f.name}));`, '        }', '    }');
    });
    lines.push('}');
    return lines.join('\n');
  });

  note = computed(() => {
    const n = this.on().length;
    const genLines = this.generated().split('\n').length;
    const mine = this.userCode().split('\n').length;
    return this.mode() === 'tostring'
      ? `The generator read the class at compile time and wrote ToString() for ${n} propert${n === 1 ? 'y' : 'ies'}. Add a property and the method updates on the next build, no reflection at run time.`
      : `You wrote ${mine} lines; the generator added ${genLines}. WPF bindings get change notifications without hand-written boilerplate (this is CommunityToolkit.Mvvm).`;
  });
}
